/** Sleeper id → line. THE storage key: an id is a person, a name is a label. */
const byId: Record<string, ProjIdpLine> = {};
/** slug → line, registered ONLY for names unique across all 963 rows. A
 *  colliding bare slug is deliberately absent rather than resolved by guess. */
const bySlug: Record<string, ProjIdpLine> = {};
let rowCount = 0;

{
  const parsed: { slug: string; id: string; line: ProjIdpLine }[] = [];
  const slugCount: Record<string, number> = {};
  for (const row of IDP_CSV.split('\n')) {
    const c = row.split(',');
    if (c.length < 14) continue;
    const slug = c[0];
    if (!slug) continue;
    const n = (i: number) => { const v = Number(c[i]); return Number.isFinite(v) ? v : 0; };
    const line: ProjIdpLine = {
      tackles: n(2), solo: n(3), tfl: n(4), sack: n(5), qbHit: n(6), pd: n(7),
      int: n(8), ff: n(9), fumRec: n(10), defTd: n(11), w2sack: n(12), w3pd: n(13),
    };
    parsed.push({ slug, id: c[1], line });
    rowCount++;
    slugCount[slug] = (slugCount[slug] ?? 0) + 1;
    if (c[1]) byId[c[1]] = line;
  }
  for (const p of parsed) if (slugCount[p.slug] === 1) bySlug[p.slug] = p.line;
}

/** The projected line for one defender, resolved by IDENTITY where identity is
 *  available and by name only where a name is unambiguous.
 *
 *  1. the caller's own Sleeper id — the pool carries one since 0205, and this
 *     branch is always right;
 *  2. an id parsed out of a slug the pool renamed to `<slug>-<sleeperId>` when
 *     two players collided, which is 0205's other half;
 *  3. a bare slug, for the 960 names that belong to exactly one man — this is
 *     what carries the 74 rookies Sleeper has not indexed.
 *
 *  A colliding bare slug with no id falls through all three and returns
 *  undefined, on purpose. */
export function idpLineFor(slug: string, sleeperId?: string | null): ProjIdpLine | undefined {
  if (sleeperId) {
    const byIdentity = byId[sleeperId];
    if (byIdentity) return byIdentity;
  }
  const renamed = /^(.+)-(\d+)$/.exec(slug);
  if (renamed) {
    const byRenamed = byId[renamed[2]];
    if (byRenamed) return byRenamed;
  }
  return bySlug[slug];
}

