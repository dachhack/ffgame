// Regenerate packages/core/src/data/playerBio.ts from Sleeper's player
// directory: slug-keyed tenure / college / jersey / age for the player card,
// plus each player's CURRENT NFL team — the baked baseline the live
// player_team_override layer (0142) diffs against. Re-run this and the
// override table shrinks to just the drift since the bake.
//
// Baked rather than fetched because the card opens from a TAP on the live
// board — the directory is ~5MB and the four fields we want from it are
// static-ish (they shift at the season boundary and on trades; re-run this
// then, same lifecycle as bakedSlugs). Slugs use the SAME normName-hyphenated
// contract as every other player key so the card resolves the board's ids.
//
// Kept to fantasy-relevant positions to hold the bake small; a slug the map
// doesn't know renders a card without the bio row, never an error.
// Usage: node scripts/gen-player-bio.mjs
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const here = new URL('.', import.meta.url).pathname;
const OUT = join(here, '..', 'packages', 'core', 'src', 'data', 'playerBio.ts');
const POS = new Set(['QB', 'RB', 'WR', 'TE', 'K', 'FB', 'DEF', 'DL', 'LB', 'DB']);

function normName(raw) {
  return String(raw)
    .toLowerCase()
    .replace(/[.'’]/g, '')
    .replace(/\b(jr|sr|ii|iii|iv|v)\b/g, '')
    .replace(/[^a-z\s-]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}
const slugOf = (n) => normName(n).replace(/\s+/g, '-');

const res = await fetch('https://api.sleeper.app/v1/players/nfl');
if (!res.ok) throw new Error(`Sleeper directory: ${res.status}`);
const dir = await res.json();

const out = {};
for (const p of Object.values(dir)) {
  const full = p.full_name || [p.first_name, p.last_name].filter(Boolean).join(' ');
  if (!full || !POS.has(p.position) || !p.active) continue;
  const slug = slugOf(full);
  if (out[slug]) continue; // first (Sleeper's canonical entry) wins on collision
  const bio = {};
  if (Number.isFinite(p.years_exp)) bio.exp = p.years_exp;
  if (p.college) bio.college = p.college;
  if (p.number != null && p.number !== '') bio.num = Number(p.number);
  if (Number.isFinite(p.age)) bio.age = p.age;
  if (p.team) bio.team = p.team;
  if (Object.keys(bio).length) out[slug] = bio;
}

const entries = Object.keys(out).sort().map((k) => `${JSON.stringify(k)}:${JSON.stringify(out[k])}`);
const ts = `// AUTO-GENERATED by scripts/gen-player-bio.mjs — do not edit by hand.
// Slug-keyed player bio from Sleeper's directory (active fantasy positions):
// exp = accrued NFL seasons (0 = rookie), college, jersey number, age, and
// team = CURRENT NFL team at bake time (the baseline the player_team_override
// live layer diffs against — data/playerTeam.ts). Baked because the player
// card opens from a tap and the live directory is ~5MB; re-run at the season
// boundary and after big trade waves. A missing slug is a card without a bio
// row, never an error.
export interface PlayerBio { exp?: number; college?: string; num?: number; age?: number; team?: string }
export const PLAYER_BIO: Record<string, PlayerBio> = {${entries.join(',')}};

/** Tenure as the card says it: "Rookie" or "Nth season" (exp seasons ACCRUED,
 *  so the current one is exp + 1). Null when the bake doesn't know the slug. */
export function tenureLabel(slug: string): string | null {
  const b = PLAYER_BIO[slug];
  if (b?.exp == null) return null;
  if (b.exp === 0) return 'Rookie';
  const n = b.exp + 1;
  const suffix = n % 10 === 1 && n % 100 !== 11 ? 'st' : n % 10 === 2 && n % 100 !== 12 ? 'nd' : n % 10 === 3 && n % 100 !== 13 ? 'rd' : 'th';
  return \`\${n}\${suffix} season\`;
}
`;
writeFileSync(OUT, ts);
console.log(`wrote ${entries.length} bios → ${OUT}`);
